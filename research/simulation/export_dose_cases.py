"""Writes frontend/tests/fixtures/daily-dose.json: today's dose for each demo zone,
with October 2025 Riyadh ET0, computed by backend/app/dose.py from the demo seed
and the reference database. Both test suites check their implementation against it.

Usage (from the repository root):  PYTHONPATH=backend .venv/bin/python research/simulation/export_dose_cases.py
"""

import json
import os
from pathlib import Path

os.environ.pop("ANBIT_SEED_SCENARIO", None)
from sqlalchemy.pool import StaticPool
from sqlmodel import SQLModel, Session, create_engine, select

from app import reference
from app.dose import daily_dose
from app.migrate import run_migrations
from app.models import SoilMeasurement, SoilProfile, Zone
from app.seed import seed_demo

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "frontend/tests/fixtures/daily-dose.json"
MONTH = 10
STRESS_BELOW_MIN = 0.009  # 0.9 percentage points, as الممر الأخضر on Home (12.9% vs 13.8%)


def main():
    engine = create_engine("sqlite://", connect_args={"check_same_thread": False}, poolclass=StaticPool)
    SQLModel.metadata.create_all(engine)
    run_migrations(engine)
    cases, stressed = [], []
    with Session(engine) as session:
        seed_demo(session)
        for zone in session.exec(select(Zone).order_by(Zone.id)).all():
            soil = session.get(SoilProfile, zone.soil_id)
            latest = session.exec(
                select(SoilMeasurement).where(SoilMeasurement.zone_id == zone.id).order_by(SoilMeasurement.measured_at.desc())
            ).first()
            need = reference.monthly_need(zone.reference_plant_id, MONTH)
            target = reference.plant_soil_target(zone.reference_plant_id, zone.soil_class)
            inputs = {
                "current_vwc": latest.value / 100,
                "target_vwc": soil.target_vwc,
                "root_depth_m": zone.root_depth_m,
                "efficiency": zone.efficiency,
                "area_m2": zone.irrigated_area_m2,
                "wetted_fraction": zone.wetted_fraction,
                "et0_mm_day": need["et0_mm_day"],
                "kc": need["kc"],
                "raw_mm": target["raw_mm"],
                "flow_lph": zone.flow_rate_lph,
                "days_to_window": 1,
                "vwc_min": soil.lower_vwc,
            }
            cases.append({"zone": zone.id, "name": zone.name, "method": zone.irrigation_method, "vwc_min": soil.lower_vwc, "inputs": inputs, "expected": daily_dose(**inputs)})
            # The same zone stressed below its minimum: the recovery dose.
            stressed_inputs = {**inputs, "current_vwc": round(soil.lower_vwc - STRESS_BELOW_MIN, 4)}
            stressed.append({"zone": zone.id, "name": zone.name, "method": zone.irrigation_method, "vwc_min": soil.lower_vwc, "inputs": stressed_inputs, "expected": daily_dose(**stressed_inputs)})
    OUT.write_text(json.dumps({"note": "Generated by research/simulation/export_dose_cases.py; October 2025 Riyadh ET0. stressed_cases: each zone 0.9 points below its minimum.", "month": MONTH, "cases": cases, "stressed_cases": stressed}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    for c in cases + stressed:
        e = c["expected"]
        print(c["zone"], c["name"], c["method"], "area", c["inputs"]["area_m2"], "eff.area", e["effective_area_m2"], "| now", round(c["inputs"]["current_vwc"] * 100, 2), "% min", c["vwc_min"],
              "| net", e["net_mm"], "mm gross", e["gross_mm"], "| L", e["litres"], "L/m2", e["litres_per_m2"], "min", e["minutes"], "| refill days", e["refill_days"], "| recovery", e["recovery"], e["recovery_events"], "| full refill L", e["full_refill_l"])


if __name__ == "__main__":
    main()
