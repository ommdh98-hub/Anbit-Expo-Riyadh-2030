// Writes frontend/lib/twin/audit-summary.json for the Reports page: the per-season
// totals of research/simulation/audit_weather_real2025.json, copied (never typed),
// plus the twin site area the audit ran on, read from the real engine.
//
// Usage (from the repository root):  node research/simulation/export_audit_summary.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve, extname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const ts = createRequire(resolve(repo, "frontend/package.json"))("typescript");
const SOURCE = resolve(repo, "research/simulation/audit_weather_real2025.json");
const OUT = resolve(repo, "frontend/lib/twin/audit-summary.json");

const cache = new Map();
function load(path) {
  if (cache.has(path)) return cache.get(path).exports;
  const mod = { exports: {} };
  cache.set(path, mod);
  const req = (n) => {
    if (!n.startsWith(".")) return createRequire(path)(n);
    const b = resolve(dirname(path), n);
    const f = [b, b + ".ts", b + ".json"].find((x) => existsSync(x));
    return extname(f) === ".json" ? JSON.parse(readFileSync(f, "utf8")) : load(f);
  };
  const out = ts.transpileModule(readFileSync(path, "utf8"), { compilerOptions: { module: 1, target: 9, esModuleInterop: true } }).outputText;
  vm.runInNewContext(out, { module: mod, exports: mod.exports, require: req, Math, Date, JSON, Set, console });
  return mod.exports;
}

const audit = JSON.parse(readFileSync(SOURCE, "utf8"));
const engine = load(resolve(repo, audit.engine, "engine.ts"));
// The audit runs defaultConfig with only season, seed, days, city and weather set.
const sections = engine.sectionsFor(engine.defaultConfig({ season: "summer", seed: 1, days: audit.days, city: audit.city, weather: audit.weather }));
const pick = (s) => ({ waterM3: s.waterM3, stressH: s.stressH, inRangePct: s.inRangePct });
const seasons = {};
for (const [key, s] of Object.entries(audit.bySeason)) {
  seasons[key] = { anbit: pick(s.anbit), sensor: pick(s.sensor), fixed: pick(s.fixed), savingVsFixedPct: s.savingVsFixedPct, savingVsSensorPct: s.savingVsSensorPct };
}
const summary = {
  note: "Generated by research/simulation/export_audit_summary.mjs from the audit file; do not edit by hand.",
  source: relative(repo, SOURCE),
  city: audit.city,
  weather: audit.weather,
  seeds: audit.seeds,
  days: audit.days,
  sections: sections.length,
  siteAreaM2: sections.reduce((t, s) => t + s.areaM2, 0),
  seasons,
};
writeFileSync(OUT, JSON.stringify(summary, null, 1) + "\n", "utf8");
console.log(`wrote ${relative(repo, OUT)}: ${summary.sections} sections, ${summary.siteAreaM2} m²`);
