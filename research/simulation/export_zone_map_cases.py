"""Writes frontend/tests/fixtures/zone-map.json: the zone view (shape, sensor points,
readings and backend coverage, including the suggested point and the coverage after
a reading there) of each demo zone, from the demo seed. The frontend map tests render
from it, so the map and the backend agree.

Usage (from the repository root):  PYTHONPATH=backend .venv/bin/python research/simulation/export_zone_map_cases.py
"""

import json
import os
from pathlib import Path

os.environ.pop("ANBIT_SEED_SCENARIO", None)
from fastapi.encoders import jsonable_encoder
from sqlalchemy.pool import StaticPool
from sqlmodel import SQLModel, Session, create_engine, select

from app import main
from app.migrate import run_migrations
from app.models import Zone
from app.seed import seed_demo

OUT = Path(__file__).resolve().parents[2] / "frontend/tests/fixtures/zone-map.json"
KEEP = ("id", "name", "x", "y", "width", "height", "area_m2", "irrigated_area_m2", "coverage_radius_m", "points", "measurements", "soil")


def main_():
    engine = create_engine("sqlite://", connect_args={"check_same_thread": False}, poolclass=StaticPool)
    SQLModel.metadata.create_all(engine)
    run_migrations(engine)
    zones = []
    with Session(engine) as session:
        seed_demo(session)
        for zone in session.exec(select(Zone).order_by(Zone.id)).all():
            view = jsonable_encoder(main.zone_view(session, zone))
            cov = view["decision"]["coverage"]
            zones.append({**{k: view[k] for k in KEEP}, "decision": {"coverage": cov}})
            print(zone.id, zone.name, f"{zone.width}x{zone.height}", "radius", zone.coverage_radius_m, "| coverage", round(cov["fraction"] * 100, 2), "->", round(cov["next_point"]["coverage_after"] * 100, 2), "at", cov["next_point"]["x"], cov["next_point"]["y"])
    OUT.write_text(json.dumps({"note": "Generated by research/simulation/export_zone_map_cases.py from the demo seed.", "zones": zones}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main_()
